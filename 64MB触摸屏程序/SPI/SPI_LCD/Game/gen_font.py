# Generate C array
# Target format for each group (4 pixel rows):
#   bytes[0..3] = left 8 pixels for rows 0,1,2,3 of this group
#   bytes[4..7] = right 8 pixels for rows 0,1,2,3 of this group
output = []
for d in range(10):
    flat = []
    for g in range(8):  # 8 groups of 4 pixel rows
        group_bytes = [0, 0, 0, 0, 0, 0, 0, 0]
        for py in range(4):  # 4 rows in this group
            row_idx = g * 4 + py
            row_val = digits[d][row_idx]
            group_bytes[py] = (row_val >> 8) & 0xFF      # left 8 pixels
            group_bytes[4 + py] = row_val & 0xFF         # right 8 pixels
        flat.extend(group_bytes)
    output.append((d, flat))

# Write output file
with open('font_data_output.txt', 'w') as f:
    f.write('const uint8_t font_digits[10][64] = {\n')
    for idx, (d, flat) in enumerate(output):
        f.write(f'    /* digit {d} */\n')
        for g in range(8):
            group_bytes = flat[g*8:(g+1)*8]
            group_str = ', '.join([f'0x{b:02X}' for b in group_bytes])
            if g < 7:
                f.write(f'        {group_str},\n')
            else:
                if idx < 9:
                    f.write(f'        {group_str},\n')
                else:
                    f.write(f'        {group_str}\n')
        if idx < 9:
            f.write(f'    }},\n')
        else:
            f.write(f'    }};\n')


def make_digit(rows):
    '''rows: 32???????, ???16????? (1=??, 0=??)'''
    data = []
    for row in rows:
        byte0 = 0
        byte1 = 0
        for i in range(16):
            if i < len(row) and row[i] == '1':
                if i < 8:
                    byte0 |= (1 << (7 - i))
                else:
                    byte1 |= (1 << (15 - i))
        data.append(byte0)
        data.append(byte1)
    return data


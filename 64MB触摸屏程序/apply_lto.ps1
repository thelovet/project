# apply_lto.ps1 - apply the frozen LTO build config to obj/*.mk + obj/makefile
#
#   * every riscv-wch-elf-gcc compile/link line gets  -flto -fno-strict-aliasing
#   * EXCEPT LCD/src/lcd.c, which is kept OUT of LTO via an explicit rule.
#
# Why lcd.c is excluded: with GCC12 + LTO the optimizer inlines lcd.c's DMA
# chain (LCD_Address_Set_DMA / LCD_DMA_Write_Buffer / SPI1 read-DMA ...) into
# callers and miscompiles the DMA handshake, so the sokoban tiles are never
# drawn on the real device.  Excluding that one TU makes LTO usable again and
# still saves ~3.0 KB.  (Details: memo.md sections 55/56.)
#
# The obj/ build files are generated by MounRiver IDE and are NOT tracked by
# git, so this config has to be re-applied before every build.  It is wire
# into the root build script (Do-Build) so both scripts and the burn tools get it.
#
# Idempotent; byte-preserving (latin1) so CN paths / file encodings stay intact.
$ErrorActionPreference = 'Stop'
$lat = [Text.Encoding]::GetEncoding(28591)

function Find-Proj([string]$startDir) {
    $d = $startDir
    for ($i = 0; $i -lt 10; $i++) {
        if (Test-Path (Join-Path $d 'SPI\SPI_LCD\User\src')) { return $d }
        $p = Split-Path $d -Parent
        if (-not $p -or $p -eq $d) { break }
        $d = $p
    }
    return ''
}
$proj = Find-Proj $PSScriptRoot
if ($proj -eq '') { Write-Host 'apply_lto: project root not found'; exit 1 }
$obj = Join-Path $proj 'SPI\SPI_LCD\obj'

$mkList = @(
    'User\src\subdir.mk', 'Startup\subdir.mk', 'Peripheral\src\subdir.mk', 'LCD\src\subdir.mk',
    'Game\games_or_menu\subdir.mk', 'Game\font_library\subdir.mk', 'Debug\subdir.mk', 'Core\subdir.mk',
    'makefile'
)

function LoadLines([string]$path) {
    $s = $lat.GetString([IO.File]::ReadAllBytes($path))
    $eol = if ($s.Contains("`r`n")) { "`r`n" } else { "`n" }
    $l = [System.Collections.Generic.List[string]]::new()
    $l.AddRange([string[]]($s -split "`r?`n"))
    return @{ path = $path; eol = $eol; lines = $l }
}
function SaveLines($o) {
    $bytes = $lat.GetBytes(($o.lines -join $o.eol))
    $old = [IO.File]::ReadAllBytes($o.path)
    if ($old.Length -eq $bytes.Length) {
        $same = $true
        for ($i = 0; $i -lt $old.Length; $i++) { if ($old[$i] -ne $bytes[$i]) { $same = $false; break } }
        if ($same) { return }   # unchanged -> don't touch mtime (keeps make incremental)
    }
    [IO.File]::WriteAllBytes($o.path, $bytes)
}

$OFF_DIR  = 'LCD/src'
$OFF_FILE = 'LCD/src/lcd.c'
$OFF_BASE = 'lcd'

foreach ($rel in $mkList) {
    $p = Join-Path $obj $rel
    if (-not (Test-Path $p)) { continue }
    $o = LoadLines $p

    # 0) drop leftover marker blocks (marker + 2 lines).
    #    NOTE: must use literal StartsWith; -like treats [ ] as a char class
    #    and would eat comment lines like "# Each subdirectory ...".
    $i = 0
    while ($i -lt $o.lines.Count) {
        $L = $o.lines[$i]
        if ($L.StartsWith('# [LTO-TEST]') -or $L.StartsWith('# [LTO-OFF]')) {
            $o.lines.RemoveAt($i)
            if ($i -lt $o.lines.Count) { $o.lines.RemoveAt($i) }
            if ($i -lt $o.lines.Count) { $o.lines.RemoveAt($i) }
        } else { $i++ }
    }

    # 1) enable LTO on every gcc line
    for ($k = 0; $k -lt $o.lines.Count; $k++) {
        $L = $o.lines[$k]
        if ($L -notlike '*riscv-wch-elf-gcc*') { continue }
        $n = [regex]::Replace($L, '\s+-flto', '')
        $n = [regex]::Replace($n, '\s+-fno-strict-aliasing', '')
        if ($n -match '-fno-common') { $n = [regex]::Replace($n, '(-fno-common)', '${1} -flto -fno-strict-aliasing') }
        elseif ($n -match '-Os ') { $n = [regex]::Replace($n, '(-Os )', '${1}-flto -fno-strict-aliasing ') }
        if ($n -ne $L) { $o.lines[$k] = $n }
    }

    # 2) keep LCD/src/lcd.c out of LTO (explicit rule overrides the pattern rule)
    if ($rel -eq 'LCD\src\subdir.mk') {
        $pi = -1
        for ($k = 0; $k -lt $o.lines.Count; $k++) { if ($o.lines[$k].StartsWith($OFF_DIR + '/%.o:')) { $pi = $k; break } }
        if ($pi -ge 0) {
            $cmd = $o.lines[$pi + 1]
            $cmdOff = [regex]::Replace($cmd, '\s+-flto', '')
            $cmdOff = [regex]::Replace($cmdOff, '\s+-fno-strict-aliasing', '')
            $ins = [string[]]@(
                '# [LTO-OFF] lcd.c excluded from LTO (GCC12 LTO miscompiles its DMA chain)',
                ($OFF_DIR + '/' + $OFF_BASE + '.o: ../' + $OFF_FILE),
                $cmdOff
            )
            $o.lines.InsertRange($pi, $ins)
        }
    }

    SaveLines $o
}
Write-Host 'apply_lto: LTO enabled on all gcc lines, LCD/src/lcd.c excluded.'

# ---- 工具链名与路径自愈(每次编译前自动执行) ----
# MounRiver IDE 编译会把 makefile 重新生成成 riscv-none-embed-*(GCC8)、且绝对路径指回工程旧位置;
# 命令行统一用 GCC12, 这里自动改回来, 免得报 "riscv-none-embed-gcc: not found" / 头文件找不到。
$selfHealFiles = @(Get-ChildItem -Path $obj -Recurse -File | Where-Object { $_.Extension -eq '.mk' -or $_.Name -eq 'makefile' })
$gbkEnc  = [Text.Encoding]::GetEncoding(936)
$utf8Enc = New-Object Text.UTF8Encoding($false)
$utf8Chk = [Text.Encoding]::GetEncoding('utf-8',[Text.EncoderFallback]::ExceptionFallback,[Text.DecoderFallback]::ExceptionFallback)
foreach ($f in $selfHealFiles) {
    $fb = [IO.File]::ReadAllBytes($f.FullName)
    $fe = $gbkEnc
    try { $null = $utf8Chk.GetString($fb); $fe = $utf8Enc } catch { }
    $fs = $fe.GetString($fb)
    $changed = $false
    if ($fs.Contains('riscv-none-embed')) { $fs = $fs.Replace('riscv-none-embed','riscv-wch-elf'); $changed = $true }
    foreach ($pair in @(@('大屏幕 - 触摸屏/','大屏幕 - 触摸屏/64MB触摸屏程序/'),
                        @('大屏幕\ -\ 触摸屏/','大屏幕\ -\ 触摸屏/64MB触摸屏程序/'),
                        @('触摸屏\SRC\Ld','触摸屏\64MB触摸屏程序\SRC\Ld'))) {
        if ($fs.Contains($pair[0]) -and -not $fs.Contains($pair[1])) { $fs = $fs.Replace($pair[0],$pair[1]); $changed = $true }
    }
    if ($changed) { [IO.File]::WriteAllText($f.FullName, $fs, $fe) }
}
/**
 * @brief  绘制16x32半宽数字
 * @param  x  起始X坐标
 * @param  y  起始Y坐标
 * @param  digit  数字 (0-9)
 * @param  color  颜色
 */
void sok_draw_digit_16x32(uint16_t x, uint16_t y, uint8_t digit, uint16_t color)
{
    if (digit > 9) return;
    uint8_t py, px;
    const uint8_t *data = font_digits[digit];
    for (py = 0; py < 32; py++) {
        uint8_t byte0 = data[py * 2];     /* 像素0-7 */
        uint8_t byte1 = data[py * 2 + 1]; /* 像素8-15 */
        for (px = 0; px < 8; px++) {
            if ((byte0 >> (7 - px)) & 0x01) {
                LCD_Address_Set(x + px, y + py, x + px, y + py);
                LCD_WR_DATA_16Bit(color);
            }
            if ((byte1 >> (7 - px)) & 0x01) {
                LCD_Address_Set(x + px + 8, y + py, x + px + 8, y + py);
                LCD_WR_DATA_16Bit(color);
            }
        }
    }
}

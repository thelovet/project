/**
 * @brief  绘制单个32x32单色字符 (数据行打包4像素行)
 * @param  x     左上角X坐标
 * @param  y     左上角Y坐标
 * @param  font  字模数据 (128字节, 8数据行×16字节, 每数据行含4像素行)
 * @param  color 前景色 (RGB565)
 */
void sok_draw_char_32(uint16_t x, uint16_t y, const uint8_t *font, uint16_t color)
{
    uint8_t py, px;
    for (py = 0; py < 32; py++) {
        uint8_t seg = 0, in = 0;
        /* 数据行号 = py/4, 行内偏移 = (py%4)*4 + px/8 */
        uint8_t line = py >> 2;
        uint8_t off  = (py & 3) << 2;
        for (px = 0; px < 32; px++) {
            uint8_t fg = (font[(uint16_t)line * FONT_CHAR_W + off + (px >> 3)] >> (7 - (px & 0x07))) & 0x01;
            if (fg && !in) { seg = px; in = 1; }
            else if (!fg && in) {
                LCD_Address_Set(x + seg, y + py, x + px - 1, y + py);
                for (; seg < px; seg++) LCD_WR_DATA_16Bit(color);
                in = 0;
            }
        }
        if (in) {
            LCD_Address_Set(x + seg, y + py, x + 31, y + py);
            for (; seg < 32; seg++) LCD_WR_DATA_16Bit(color);
        }
    }
}


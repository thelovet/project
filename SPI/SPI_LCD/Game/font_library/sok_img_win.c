/**
 * @brief  绘制16x32半宽数字字符
 *         字体格式: 32行 x 2字节/行, 每行: 左8像素字节 + 右8像素字节, MSB=左像素
 * @param  x     左上角X坐标
 * @param  y     左上角Y坐标
 * @param  digit 数字 (0-9), 直接作为字体索引
 * @param  color 前景色 (RGB565)
 */
void sok_draw_digit_16x32(uint16_t x, uint16_t y, uint8_t digit, uint16_t color)
{
    if (digit > 9) return;
    /* 优先从外部Flash读取字模, 烧录模式下回退内部Flash */
    const uint8_t *data = FlashStore_ResLoad(FLASH_STORE_ID_DIGITS,
                                             (uint32_t)digit * FONT_DIGIT_BYTES,
                                             FONT_DIGIT_BYTES);
    if (!data) data = &font_digits[digit * FONT_DIGIT_BYTES];
    uint8_t py, px;
    for (py = 0; py < 32; py++) {
        uint8_t left_byte  = data[py * 2];
        uint8_t right_byte = data[py * 2 + 1];
        uint8_t seg = 0, in_seg = 0;
        uint8_t start_px = 0;
        /* 处理左8像素 (MSB=位7对应x+0) */
        for (px = 0; px < 8; px++) {
            if (((left_byte >> (7 - px)) & 0x01) && !in_seg) {
                start_px = px; in_seg = 1;
            } else if (!((left_byte >> (7 - px)) & 0x01) && in_seg) {
                LCD_Address_Set(x + start_px, y + py, x + px - 1, y + py);
                for (seg = start_px; seg < px; seg++) LCD_WR_DATA_16Bit(color);
                in_seg = 0;
            }
        }
        if (in_seg) {
            LCD_Address_Set(x + start_px, y + py, x + 7, y + py);
            for (seg = start_px; seg < 8; seg++) LCD_WR_DATA_16Bit(color);
            in_seg = 0;
        }
        /* 处理右8像素 (MSB=位7对应x+8) */
        for (px = 0; px < 8; px++) {
            if (((right_byte >> (7 - px)) & 0x01) && !in_seg) {
                start_px = px; in_seg = 1;
            } else if (!((right_byte >> (7 - px)) & 0x01) && in_seg) {
                LCD_Address_Set(x + start_px + 8, y + py, x + px + 7, y + py);
                for (seg = start_px; seg < px; seg++) LCD_WR_DATA_16Bit(color);
                in_seg = 0;
            }
        }
        if (in_seg) {
            LCD_Address_Set(x + start_px + 8, y + py, x + 15, y + py);
            for (seg = start_px; seg < 8; seg++) LCD_WR_DATA_16Bit(color);
        }
    }
}



/**
 * @brief  绘制关卡编号 "关卡X" (32x32中文 + 16x32半宽数字, 居中显示)
 */
void sok_level_draw(uint8_t level, uint16_t color)
{
    LCD_CS_CLR;

    uint8_t tens = level / 10;
    uint8_t ones = level % 10;
    uint8_t digit_count = (tens > 0) ? 2 : 1;
    uint8_t digit_w = digit_count * 16 + (digit_count - 1) * 2;

    /* "关卡" 两个32x32 + 数字(16x32, 与中文同高) */
    uint16_t total_w = 64 + 4 + digit_w;
    uint16_t x = (240 - total_w) / 2;
    uint16_t y = (240 - 32) / 2 - 20;

    /* 绘制 "关" */
    sok_draw_char_32(x, y, FlashStore_ResLoad(FLASH_STORE_ID_32_GUAN, 0, FONT_CHAR_SIZE), color);
    /* 绘制 "卡" */
    sok_draw_char_32(x + 32, y, FlashStore_ResLoad(FLASH_STORE_ID_32_KA, 0, FONT_CHAR_SIZE), color);

    /* 绘制数字 (16x32, 与中文顶部对齐) */
    uint16_t dx = x + 64 + 4;
    if (tens > 0) {
        sok_draw_digit_16x32(dx, y, tens, color);
        dx += 16 + 2;
    }
    sok_draw_digit_16x32(dx, y, ones, color);

    LCD_CS_SET;
}

/**
 * @brief  缩放绘制16x32数字 (最近邻采样)
 * @param  x       左上角X
 * @param  y       左上角Y
 * @param  digit   数字 (0-9)
 * @param  color   前景色
 * @param  tw      目标宽度 (px)
 * @param  th      目标高度 (px)
 */
void sok_draw_digit_scaled(uint16_t x, uint16_t y, uint8_t digit,
                           uint16_t color, uint8_t tw, uint8_t th)
{
    if (digit > 9 || tw == 0 || th == 0) return;

    /* 优先从外部Flash读取字模, 烧录模式下回退内部Flash */
    const uint8_t *data = FlashStore_ResLoad(FLASH_STORE_ID_DIGITS,
                                             (uint32_t)digit * FONT_DIGIT_BYTES,
                                             FONT_DIGIT_BYTES);
    if (!data) data = &font_digits[digit * FONT_DIGIT_BYTES];
    uint8_t ty, tx;

    for (ty = 0; ty < th; ty++) {
        uint8_t sy     = (uint16_t)ty * 32 / th;
        uint8_t left   = data[sy * 2];
        uint8_t right  = data[sy * 2 + 1];

        uint8_t run_start = 0, in_run = 0;
        for (tx = 0; tx < tw; tx++) {
            uint8_t sx = (uint16_t)tx * 16 / tw;
            uint8_t byte_val = (sx < 8) ? left : right;
            uint8_t bit = 7 - (sx & 7);
            uint8_t pixel = (byte_val >> bit) & 0x01;

            if (pixel && !in_run) { run_start = tx; in_run = 1; }
            else if (!pixel && in_run) {
                LCD_Address_Set(x + run_start, y + ty, x + tx - 1, y + ty);
                uint16_t i;
                for (i = run_start; i < tx; i++) LCD_WR_DATA_16Bit(color);
                in_run = 0;
            }
        }
        if (in_run) {
            LCD_Address_Set(x + run_start, y + ty, x + tw - 1, y + ty);
            uint16_t i;
            for (i = run_start; i < tw; i++) LCD_WR_DATA_16Bit(color);
        }
    }
}